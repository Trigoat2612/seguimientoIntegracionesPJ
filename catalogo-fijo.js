export const catalogKey=value=>String(value??'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[\u00ad*]/g,'').toUpperCase().replace(/[^A-Z0-9]+/g,' ').trim();
export function linkCatalogItem(item,systems){
 if(!Array.isArray(systems)||!systems.length)return {system:null,reason:'Pendiente de sincronización'};
 const alias=CATALOGO_ALIASES[item.nombre];
 const lookup=alias||item.nombre;
 const matched=systems.filter(s=>catalogKey(s.name)===catalogKey(lookup));
 if(matched.length===1)return {system:matched[0],reason:alias?'Equivalencia explícita (revisable)':'Coincidencia de nombre',shared: item.nombre==='CONADIS'||item.nombre==='SUNAT'};
 return {system:null,reason:matched.length>1?'Equivalencia ambigua':'Sin correspondencia confirmada'};
}
