import assert from 'node:assert/strict';
import {entityFromColumnE,entityPresentation,integrationWithEntity} from '../ppt-entities.js';
import {parseTactical} from '../tactical.js';
import {buildTacticalSlidePlan,itemLabel} from '../ppt-layout.js';
const group=(...e)=>[e.map(entry=>({entry,height:0.25}))];
const pj={id:'e1',name:'Elevación Suprema',dependency:'PJ',status:'Sin clasificar',statusRaw:'Manual'};
const same={id:'e2',name:'Consulta',dependency:'PJ'};
const other={id:'e3',name:'API GTI',dependency:'GTI / SOFTPLAN'};
const empty={id:'e4',name:'Sin dependencia',dependency:''};
assert.equal(entityFromColumnE(other),'GTI / SOFTPLAN');
assert.deepEqual(entityPresentation(group(pj,same)),{header:'PJ',perIntegration:false});
assert.deepEqual(entityPresentation(group(pj,other)),{header:'',perIntegration:true});
assert.deepEqual(entityPresentation(group(pj,empty)),{header:'',perIntegration:true});
assert.deepEqual(entityPresentation(group(empty)),{header:'',perIntegration:true});
assert.deepEqual(entityPresentation(group()),{header:'',perIntegration:false});
assert.equal(integrationWithEntity(other,true),'API GTI · Entidad: GTI / SOFTPLAN');
assert.equal(integrationWithEntity(other,false),'API GTI');
assert.equal(integrationWithEntity(empty,true),'Sin dependencia');
assert.equal(itemLabel(other,true),'API GTI · Entidad: GTI / SOFTPLAN');
// Verificar la ruta de datos real: Seguimiento!E -> entry.dependency -> exportación
const rows=Array.from({length:38},()=>[]);
rows[0][1]='Integración';rows[0][3]='Estado';rows[0][11]='Criticidad';
rows[1][1]='RENIEC';rows[1][3]='Validada';rows[1][4]='GSJ';rows[1][11]='Alta';
rows[2][1]='SUNAT';rows[2][3]='Validada';rows[2][4]='GTI / SOFTPLAN';rows[2][11]='Alta';
rows[3][1]='Manual 1';rows[3][3]='manual';rows[3][4]='SGE';
rows[4][1]='Manual 2';rows[4][3]='manual';rows[4][4]='PJ';
const data=parseTactical(new Map([['Seguimiento',rows]]));
const plan=buildTacticalSlidePlan({category:{id:'todas'},primary:data.entries.filter(e=>e.high),nonPrioritized:data.entries.filter(e=>!e.high),manualEntries:data.entries.filter(e=>e.statusRaw==='manual')});
assert.equal(plan.pages[0].parts['Validada'].flat()[0].entry.dependency,'GSJ');
assert.equal(plan.pages[0].parts['Validada'].flat()[1].entry.dependency,'GTI / SOFTPLAN');
assert.deepEqual(entityPresentation(plan.pages[0].parts['Validada']),{header:'',perIntegration:true});
assert.equal(entityPresentation(plan.pages[0].parts.Manual).header,'');
assert.equal(plan.pages.length,1);
assert.equal(plan.pages[0].parts.Manual.flat().find(x=>x.entry.id==='seg-5').entry.dependency,'PJ');
assert.equal(integrationWithEntity(plan.pages[0].parts.Manual[0][0].entry,true),'Manual 1 · Entidad: SGE');
console.log('Columna E: literal, sin agregación por separadores ni PJ por defecto; paneles mixtos por integración.');
